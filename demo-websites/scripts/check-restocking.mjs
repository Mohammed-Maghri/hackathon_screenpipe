import assert from 'node:assert/strict'
import { build } from 'esbuild'
const built=await build({entryPoints:['demo-websites/lib/restocking.ts'],bundle:true,format:'esm',write:false})
const {recommendRestock,restockDefaults}=await import('data:text/javascript;base64,'+Buffer.from(built.outputFiles[0].text).toString('base64'))
const product={id:'a',name:'A',stock:2,unitCost:5,supplier:'Demo',leadDays:3,incoming:4,incomingDate:'2026-10-21'}
const sales=[{id:'1',productId:'a',quantity:28,date:'2026-10-10',status:'Paid'},{id:'2',productId:'a',quantity:99,date:'2026-10-11',status:'Cancelled'},{id:'3',productId:'a',quantity:99,date:'2026-10-12',status:'Processing'},{id:'4',productId:'a',quantity:99,date:'2026-10-19',status:'Paid'}]
const result=recommendRestock([product],sales,restockDefaults)
assert.equal(result.rows[0].dailyRate,2)
assert.equal(result.rows[0].targetStock,24)
assert.equal(result.rows[0].buy,18)
assert.equal(result.rows[0].cost,90)
assert.equal(result.rows[0].urgent,true,'Shortage before incoming arrival must stay urgent')
assert.equal(recommendRestock([{...product,stock:100}],sales,restockDefaults).rows[0].buy,0)
assert.equal(recommendRestock([{...product,incomingDate:'2026-11-30'}],sales,restockDefaults).rows[0].buy,22)
assert.equal(recommendRestock([{...product,incomingDate:'2026-10-18'}],sales,restockDefaults).rows[0].eligibleIncoming,0)
assert.equal(recommendRestock([{...product,incomingDate:''}],sales,restockDefaults).rows[0].eligibleIncoming,0)
assert.equal(recommendRestock([product],[],restockDefaults).rows[0].buy,0)
assert.match(recommendRestock([product],[],restockDefaults).rows[0].warning,/No sales/)
assert.match(recommendRestock([{...product,stock:130}],sales,restockDefaults).rows[0].warning,/60 days/)
assert.equal(recommendRestock([product],sales,{...restockDefaults,budget:20}).overBudget,true)
assert.equal(recommendRestock([product],sales,{...restockDefaults,budget:20}).rows[0].buy,18,'Budget must not silently shrink quantities')
assert.throws(()=>recommendRestock([product,product],sales,restockDefaults),/Duplicate/)
assert.throws(()=>recommendRestock([product],[sales[0],sales[0]],restockDefaults),/Duplicate/)
assert.throws(()=>recommendRestock([{...product,stock:-1}],sales,restockDefaults),/Stock/)
assert.throws(()=>recommendRestock([product],sales,{...restockDefaults,end:'2026-02-30'}),/dates/)
assert.throws(()=>recommendRestock([product],sales,{...restockDefaults,end:restockDefaults.asOf}),/before/)
console.log('PASS restocking: sales eligibility, zero-sale days, delivery cutoff/unknown/overdue ETA, shortage before arrival, inventory changes, costs, budget warning, slow/no sales, invalid inputs and duplicate IDs.')
